// loom2v — BUILD-TIME tool. Generates gen/loom_gen.v: the Loom wiring for each
// application partition from [[component]] in ecu.toml. For each partition it
// emits a state struct (component instances), one glue handler per
// [[component.handler]] (acquire input signals -> call the component method ->
// publish output signals, using each channel's configured transport), and a
// `partition_<name>` entry that registers the handlers on a loom.Scheduler.
// This replaces hand-written partition glue. Convention: a port name P maps to
// the V type `app.P` and the IOC channel `gen.<snake(P)>_ch`.
//
//   v run tools/loom2v/gen.v config/ecu.toml gen/loom_gen.v
module main

import os
import toml

fn main() {
	args := os.args
	if args.len < 3 {
		eprintln('usage: loom2v <ecu.toml> <out.v>')
		exit(2)
	}
	doc := toml.parse_file(args[1]) or { panic('parse ${args[1]}: ${err}') }

	// port/channel -> transport (from [[ioc]])
	mut tr_of := map[string]string{}
	for ch in doc.value('ioc').array() {
		m := ch.as_map()
		tr_of[(m['name'] or { toml.Any('') }).string()] = (m['transport'] or { toml.Any('double') }).string()
	}
	// partition -> core (from [[partition]])
	mut core_of := map[string]int{}
	for p in doc.value('partition').array() {
		m := p.as_map()
		core_of[(m['name'] or { toml.Any('') }).string()] = int((m['core'] or { toml.Any(0) }).int())
	}
	// group components by partition
	mut by_part := map[string][]toml.Any{}
	for c in doc.value('component').array() {
		part := (c.as_map()['partition'] or { toml.Any('') }).string()
		by_part[part] << c
	}

	mut b := []string{}
	b << '// Code generated by tools/loom2v from ${os.file_name(args[1])} — DO NOT EDIT.'
	b << '// Loom wiring per application partition: state, handler glue, scheduled entry.'
	b << 'module gen'
	b << ''
	b << 'import app'
	b << 'import loom'
	b << 'import osal'

	for part, clist in by_part {
		// --- partition state struct: one field per component ---
		b << ''
		b << 'struct Partition_${part}_state {'
		b << 'mut:'
		for c in clist {
			cname := (c.as_map()['name'] or { toml.Any('') }).string()
			b << '\t${snake(cname)} app.${cname}'
		}
		b << '}'

		// --- one glue handler per component handler; collect scheduler registrations ---
		mut regs := []string{}
		for c in clist {
			cm := c.as_map()
			cname := (cm['name'] or { toml.Any('') }).string()
			field := snake(cname)
			for h in (cm['handler'] or { toml.Any([]toml.Any{}) }).array() {
				hm := h.as_map()
				hname := (hm['name'] or { toml.Any('') }).string()
				period_us := int((hm['period_ms'] or { toml.Any(0) }).int()) * 1000
				glue := 'handler_${part}_${field}_${hname}'

				b << ''
				b << 'fn ${glue}(ctx voidptr) {'
				b << '\tmut st := unsafe { &Partition_${part}_state(ctx) }'
				mut call_args := []string{}
				for ri, r in (hm['reads'] or { toml.Any([]toml.Any{}) }).array() {
					rn := r.string()
					b << '\tmut r${ri} := app.${rn}{}'
					b << '\tosal.${acquire_fn(tr_of[rn] or { 'double' })}(${snake(rn)}_ch, &r${ri}, u8(sizeof(r${ri})))'
					call_args << 'r${ri}'
				}
				mut pubs := []string{}
				for wi, w in (hm['writes'] or { toml.Any([]toml.Any{}) }).array() {
					wn := w.string()
					b << '\tmut w${wi} := app.${wn}{}'
					call_args << 'mut w${wi}'
					pubs << '\tosal.${publish_fn(tr_of[wn] or { 'double' })}(${snake(wn)}_ch, &w${wi}, u8(sizeof(w${wi})))'
				}
				b << '\tst.${field}.${hname}(${call_args.join(', ')})'
				for p in pubs {
					b << p
				}
				b << '}'
				regs << '\tsched.every(${period_us}, ${glue}, &st)'
			}
		}

		// --- partition entry (CoreEntry signature for osal.start_core/spawn) ---
		b << ''
		b << 'pub fn partition_${part}(core int, arg voidptr) {'
		b << '\tosal.pin_to_core(${core_of[part] or { 0 }})'
		b << '\tmut st := Partition_${part}_state{}'
		b << '\tmut sched := loom.Scheduler{}'
		for r in regs {
			b << r
		}
		b << '\tfor {'
		b << '\t\tsched.run(osal.now_us())'
		b << '\t\tosal.sleep_us(1000)'
		b << '\t}'
		b << '}'
	}

	os.write_file(args[2], b.join('\n') + '\n') or { panic('write ${args[2]}: ${err}') }
	eprintln('loom2v: ${by_part.len} app partition(s) -> ${args[2]}')
}

// transport -> osal call. seqlock=write/read, triple=publish/acquire,
// double (and host fallbacks dma/hw_sem/mailbox)=publish2/acquire2.
fn acquire_fn(tr string) string {
	return match tr {
		'seqlock' { 'ioc_read' }
		'triple' { 'ioc_acquire' }
		else { 'ioc_acquire2' }
	}
}

fn publish_fn(tr string) string {
	return match tr {
		'seqlock' { 'ioc_write' }
		'triple' { 'ioc_publish' }
		else { 'ioc_publish2' }
	}
}

fn snake(name string) string {
	mut out := []u8{}
	for i, c in name {
		is_upper := c >= `A` && c <= `Z`
		if is_upper && i > 0 {
			prev := name[i - 1]
			if (prev >= `a` && prev <= `z`) || (prev >= `0` && prev <= `9`) {
				out << `_`
			}
		}
		if (c >= `a` && c <= `z`) || (c >= `0` && c <= `9`) {
			out << c
		} else if is_upper {
			out << c + 32
		} else {
			out << `_`
		}
	}
	return out.bytestr()
}

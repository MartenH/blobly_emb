module main

import os
import json2

// Meta is one source file as one test build instrumented it (V's -coverage meta/<fhash>.json).
// `points` are line numbers; a counter row names a point by its index here.
struct Meta {
	file          string
	fhash         string
	build_options string
	points        []int
}

// Cov is one source file's statement coverage: points its OWN tests (the _test.v files in its
// directory, i.e. its V module) reached, and points any test reached.
struct Cov {
mut:
	file   string
	points int
	own    int
	any    int
	built  bool // compiled by some host test; false = no point data at all
}

fn (c Cov) own_pct() f64 {
	return if c.points == 0 { 100.0 } else { f64(c.own) * 100.0 / f64(c.points) }
}

fn (c Cov) any_pct() f64 {
	return if c.points == 0 { 100.0 } else { f64(c.any) * 100.0 / f64(c.points) }
}

// test_of is the _test.v a build was made for: the last argument of its build options, an
// absolute path (taken from its last ' /', so a path with a space in it stays whole).
fn test_of(build_options string) string {
	o := build_options.trim_space()
	i := o.last_index(' /') or { return o }
	return o[i + 1..]
}

// hits reads every vcounters_*.csv in dir into fhash -> point indices with a nonzero count.
fn hits(dir string) map[string]map[int]bool {
	mut out := map[string]map[int]bool{}
	for f in os.ls(dir) or { []string{} } {
		if !f.starts_with('vcounters_') || !f.ends_with('.csv') {
			continue
		}
		text := os.read_file(os.join_path(dir, f)) or { continue }
		for ln in text.split_into_lines() {
			if ln.starts_with('#') || ln.starts_with('meta,') || ln == '' {
				continue
			}
			parts := ln.split(',')
			if parts.len != 3 || parts[2].u64() == 0 {
				continue
			}
			if parts[0] !in out {
				out[parts[0]] = map[int]bool{}
			}
			out[parts[0]][parts[1].int()] = true
		}
	}
	return out
}

// metas reads every meta/*.json under dir.
fn metas(dir string) []Meta {
	mut out := []Meta{}
	mdir := os.join_path(dir, 'meta')
	for f in os.ls(mdir) or { []string{} } {
		if !f.ends_with('.json') {
			continue
		}
		text := os.read_file(os.join_path(mdir, f)) or { continue }
		m := json2.decode[Meta](text) or { continue }
		out << m
	}
	return out
}

// attribute folds every build of every in-scope file into one Cov per file, by LINE: each test
// build instruments the file on its own, so a point's index is that build's and only its line
// is shared. A file's points are every line any build instrumented; a line is covered when any
// build reached it, and covered by OWN tests when a build made for a test in the file's own
// directory reached it. `rel` maps an absolute path to the repo-relative one, or '' for a file
// outside the scope.
fn attribute(ms []Meta, hit map[string]map[int]bool, rel fn (string) string) map[string]Cov {
	mut all := map[string]map[int]bool{}
	mut own := map[string]map[int]bool{}
	mut any := map[string]map[int]bool{}
	for m in ms {
		r := rel(m.file)
		if r == '' {
			continue
		}
		if r !in all {
			all[r] = map[int]bool{}
			own[r] = map[int]bool{}
			any[r] = map[int]bool{}
		}
		for line in m.points {
			all[r][line] = true
		}
		is_own := os.dir(os.real_path(m.file)) == os.dir(os.real_path(test_of(m.build_options)))
		for idx, _ in hit[m.fhash] or { map[int]bool{} } {
			if idx < 0 || idx >= m.points.len {
				continue
			}
			line := m.points[idx]
			any[r][line] = true
			if is_own {
				own[r][line] = true
			}
		}
	}
	mut out := map[string]Cov{}
	for r, lines in all {
		out[r] = Cov{
			file:   r
			points: lines.len
			own:    own[r].len
			any:    any[r].len
			built:  true
		}
	}
	return out
}

// render is docs/coverage.md: a function of the measurement only, so a regeneration that
// changes nothing changes no byte.
fn render(covs []Cov) string {
	mut b := []string{}
	b << '<!-- Generated by tools/cover (make coverage) — DO NOT EDIT. -->'
	b << '# Unit coverage'
	b << ''
	b << 'Statement coverage of the code that goes into an image, from the host unit tests (V\'s'
	b << '`-coverage`). **own** counts only the tests in the file\'s own directory (its V module);'
	b << '**any** counts every test, so a module reached only through another module\'s tests shows'
	b << 'the difference. The **own** column is a ratchet: `make coverage-check` fails when a file'
	b << 'drops below what is recorded here, and CI fails when this file is stale.'
	b << ''
	mut tp := 0
	mut to := 0
	mut ta := 0
	mut unbuilt := 0
	for c in covs {
		if c.built {
			tp += c.points
			to += c.own
			ta += c.any
		} else {
			unbuilt++
		}
	}
	tot := Cov{
		points: tp
		own:    to
		any:    ta
	}
	b << '| files measured | not built by a host test | points | own | any |'
	b << '|---|---|---|---|---|'
	b << '| ${covs.len - unbuilt} | ${unbuilt} | ${tp} | ${pct(tot.own_pct())} | ${pct(tot.any_pct())} |'
	b << ''
	b << '| file | points | own covered | own | any |'
	b << '|---|---|---|---|---|'
	for c in covs {
		if c.built {
			b << '| ${c.file} | ${c.points} | ${c.own} | ${pct(c.own_pct())} | ${pct(c.any_pct())} |'
		} else {
			b << '| ${c.file} | — | — | not built | not built |'
		}
	}
	b << ''
	return b.join('\n')
}

fn pct(p f64) string {
	return '${p:.1f}%'
}

// parse_recorded reads the per-file rows of a docs/coverage.md back: file -> own percent, or
// -1 for a file recorded as not built.
fn parse_recorded(text string) map[string]f64 {
	mut out := map[string]f64{}
	for ln in text.split_into_lines() {
		cells := ln.split('|').map(it.trim_space())
		// | file | points | own covered | own | any |  ->  ['', file, points, covered, own, any, '']
		if cells.len != 7 || !cells[1].ends_with('.v') {
			continue
		}
		out[cells[1]] = if cells[4] == 'not built' { -1.0 } else { cells[4].trim_right('%').f64() }
	}
	return out
}

// drops are the files whose own coverage fell below the recorded value, or that were measured
// and are no longer built. Compared at the rendered precision, so a value that prints the same
// is the same.
fn drops(recorded map[string]f64, covs []Cov) []string {
	mut out := []string{}
	for c in covs {
		was := recorded[c.file] or { continue }
		if !c.built {
			if was >= 0 {
				out << '${c.file}: ${pct(was)} -> not built by any host test'
			}
			continue
		}
		now := pct(c.own_pct()).trim_right('%').f64()
		if was >= 0 && now < was {
			out << '${c.file}: ${pct(was)} -> ${pct(now)} (own tests)'
		}
	}
	return out
}
